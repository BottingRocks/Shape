//! Signal-finder coverage map of one frozen seed.
//!
//! Runs contracts + routing + package finders on emoji-channel-sample-halves-match-media-layout through
//! `analyze_program_signals`, joins every slot's producer/callback spans with
//! the package-finder claims, and joins the slot address with the verified
//! identity of `tests/fixtures/signals/verified/emoji-channel-sample-halves-match-media-layouts/slot-map.json`
//! using canonical signal identities. Writes the
//! table to `docs/signals/signal-finder-coverage.md`.
//!
//! Env-gated: `SHAPE_FROZEN_ROOT` (default `/tmp/shape-corpus-ten-fresh`);
//! skips when the corpus is absent.
//!
//! ```text
//! cargo test --profile iter --test program_signal_coverage -- --ignored --nocapture
//! ```

#[path = "support/frozen_signal_layout.rs"]
mod frozen_signal_layout;

use std::collections::BTreeMap;
use std::fmt::Write as _;

use shape::signals::analysis::{analyze_program_signals, Routing, SignalFinderOptions};

const LABEL: &str = "emoji-channel-sample-halves-match-media-layout";

#[test]
#[ignore = "needs the frozen corpus-ten corpus"]
fn frozen_program_signal_finder_coverage() {
    let Some(program) = frozen_signal_layout::layout_program(LABEL) else {
        eprintln!(
            "skip: {LABEL} program not found under {}",
            frozen_signal_layout::frozen_root().display()
        );
        return;
    };
    let source = std::fs::read_to_string(&program).expect("program");
    let analysis =
        analyze_program_signals(&source, &SignalFinderOptions::default()).expect("analysis");
    let identities = frozen_signal_layout::layout_identities(LABEL);

    let mut table = String::new();
    let mut touched = 0usize;
    let mut touched_enclosing = 0usize;
    let mut identified = 0usize;
    let mut canonical_count: BTreeMap<&str, usize> = BTreeMap::new();
    for slot in &analysis.slots {
        let canonical = identities
            .get(&slot.address)
            .map(String::as_str)
            .unwrap_or("-");
        if canonical != "-" {
            identified += 1;
            *canonical_count.entry(canonical).or_default() += 1;
        }
        let routing = match &slot.routing {
            Routing::Positional(index) => format!("positional {index}"),
            Routing::Name(name) => format!("name {name}"),
        };
        if !slot.slot_roles.is_empty() {
            touched += 1;
        }
        if !slot.roles_enclosing.is_empty() {
            touched_enclosing += 1;
        }
        let shapes: Vec<String> = slot
            .layout
            .messages
            .iter()
            .map(|message| message.fields.len().to_string())
            .collect();
        writeln!(
            table,
            "| `{}` | {} | {} | {} | {:?} | {} | {} | {} | {} |",
            slot.address,
            slot.descriptor,
            routing,
            canonical,
            slot.contract_status,
            shapes.join("/"),
            list(&slot.slot_roles),
            slot.roles_inside.len(),
            list(&slot.roles_enclosing),
        )
        .unwrap();
    }
    let duplicates: Vec<String> = canonical_count
        .iter()
        .filter(|(_, count)| **count > 1)
        .map(|(name, count)| format!("{name} x{count}"))
        .collect();

    let mut doc = String::new();
    writeln!(doc, "# Signal finder coverage: {LABEL}\n").unwrap();
    writeln!(
        doc,
        "Generated by `tests/program_signal_coverage.rs` \
         (`cargo test --profile iter --test program_signal_coverage -- --ignored --nocapture`). \
         Do not edit by hand.\n"
    )
    .unwrap();
    writeln!(
        doc,
        "Input: `{}` (sha256 `{}`). Identity: `tests/fixtures/signals/verified/emoji-channel-sample-halves-match-media-layouts/slot-map.json` \
         using canonical signal identities. \
         Roles are `finders::run_all` claims. `slot roles`: for each of the slot's own sites \
         (emission and error/complete sites, the caller-side write of every value, value sources and \
         definitions inside the producer/callbacks) the innermost claimed function containing it, \
         when that function lies inside the producer or a callback. `producer-wide roles`: the count \
         of all claims inside the producer and callbacks (a group body is shared by its whole row, \
         so this count is the same for every slot of a row). `roles enclosing`: claims strictly \
         enclosing the producer.\n",
        program.file_name().unwrap().to_string_lossy(),
        analysis.report.source.sha256
    )
    .unwrap();
    writeln!(doc, "## Summary\n").unwrap();
    writeln!(doc, "- slots: {}", analysis.slots.len()).unwrap();
    writeln!(doc, "- slots with a verified identity: {identified}").unwrap();
    writeln!(doc, "- slots with at least one slot role: {touched}").unwrap();
    writeln!(
        doc,
        "- slots with a finder role enclosing the producer: {touched_enclosing}"
    )
    .unwrap();
    writeln!(
        doc,
        "- canonical names occurring more than once: {}",
        if duplicates.is_empty() {
            "none".to_string()
        } else {
            duplicates.join(", ")
        }
    )
    .unwrap();
    writeln!(doc, "\n## Slots\n").unwrap();
    writeln!(
        doc,
        "`fields` is the top-level field count of each distinct message layout.\n"
    )
    .unwrap();
    writeln!(
        doc,
        "| address | descriptor | routing | canonical | contract | fields | slot roles | producer-wide roles | roles enclosing |"
    )
    .unwrap();
    writeln!(doc, "|---|---|---|---|---|---|---|---|---|").unwrap();
    doc.push_str(&table);

    let out = frozen_signal_layout::repo_root().join("docs/signals/signal-finder-coverage.md");
    std::fs::create_dir_all(out.parent().unwrap()).expect("docs/signals");
    std::fs::write(&out, &doc).expect("write coverage");
    eprintln!("{doc}");
    eprintln!("wrote {}", out.display());

    assert_eq!(
        identified,
        identities.len(),
        "every slot-map address is a slot"
    );
}

fn list(roles: &[&str]) -> String {
    if roles.is_empty() {
        "".into()
    } else {
        roles
            .iter()
            .map(|role| format!("`{role}`"))
            .collect::<Vec<_>>()
            .join(", ")
    }
}
